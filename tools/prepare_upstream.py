#!/usr/bin/env python3
"""Import the pinned upstream Android payload, never the upstream Android shell.

The APK is used as the reproducible distribution of Android-adapted PI resources,
CPython/OpenCV/NumPy and matching MaaFramework libraries. Source: upstream.lock.json.
"""
from __future__ import annotations

import argparse
import hashlib
import io
import json
from pathlib import Path, PurePosixPath
import shutil
import subprocess
import tempfile
import zipfile

ROOT = Path(__file__).resolve().parents[1]
MARKER = ".maafgo-generated.json"
LOADING_TIMEOUT_SECONDS = 1800


def adapt_loading_waits(project):
    """Allow on-demand game downloads without changing click/retry budgets."""
    loading_nodes = {
        "打开游戏", "自动登录", "自动登录2", "自动登录_蓝屏检测继续",
        "直到达到主界面", "确认抵达主界面流程", "登录流程持续识别",
        "进本流程", "进本-实际点击队伍确认", "进本-开始后弹窗检查",
        "进本-开始按钮已消失", "进本-等待战斗主界面或剧情",
    }
    for path in (project / "resource").rglob("pipeline/*.json"):
        nodes = json.loads(path.read_text(encoding="utf-8-sig"))
        changed = False
        for name, node in nodes.items():
            if name in loading_nodes:
                node["timeout"] = LOADING_TIMEOUT_SECONDS * 1000
                changed = True
            if name == "主线-配置":
                node.setdefault("attach", {})["transition_timeout"] = LOADING_TIMEOUT_SECONDS
                changed = True
        if changed:
            path.write_text(json.dumps(nodes, ensure_ascii=False, indent=2) + "\n")

    # Pin each source replacement: upstream changes must be reviewed, not silently
    # packaged with a timeout that its Python validator rejects.
    replacements = {
        "agent/custom/main_story_action.py": {
            "not 10 <= self.timeout <= 600": "not 10 <= self.timeout <= 3600",
            "until = self.clock() + 5": "until = self.clock() + self.timeout",
        },
        "agent/battle/runtime/runtime.py": {
            "_ANIMATION_TIMEOUT_S = 120.0": f"_ANIMATION_TIMEOUT_S = {LOADING_TIMEOUT_SECONDS}.0",
            "_UNKNOWN_TIMEOUT_S = 30.0": f"_UNKNOWN_TIMEOUT_S = {LOADING_TIMEOUT_SECONDS}.0",
        },
    }
    for relative, changes in replacements.items():
        path = project / relative
        source = path.read_text()
        for old, new in changes.items():
            if source.count(old) != 1:
                raise ValueError(f"Upstream loading wait changed: {relative}: {old}")
            source = source.replace(old, new)
        compile(source, relative, "exec")
        path.write_text(source)


def digest(path):
    with path.open("rb") as stream:
        return hashlib.file_digest(stream, "sha256").hexdigest()


def unpack(archive, destination, prefix=""):
    for member in archive.infolist():
        if not member.filename.startswith(prefix):
            continue
        name = member.filename[len(prefix):]
        path = PurePosixPath(name)
        if path.is_absolute() or ".." in path.parts or "\\" in name:
            raise ValueError(f"Unsafe archive path: {name}")
        if not name or member.is_dir():
            continue
        target = destination.joinpath(*path.parts)
        target.parent.mkdir(parents=True, exist_ok=True)
        with archive.open(member) as src, target.open("wb") as dst:
            shutil.copyfileobj(src, dst)


def publish(source, target):
    # Only replace directories previously generated by this tool.
    if target.exists():
        if not (target / MARKER).is_file():
            raise ValueError(f"Refusing to replace unmanaged directory: {target}")
        shutil.rmtree(target)
    target.parent.mkdir(parents=True, exist_ok=True)
    shutil.move(str(source), str(target))


def prepare(apk=None):
    lock = json.loads((ROOT / "upstream.lock.json").read_text())
    cache = ROOT / ".cache"
    cache.mkdir(exist_ok=True)
    if apk is None:
        apk = cache / lock["url"].rsplit("/", 1)[-1]
        if not apk.exists():
            partial = apk.with_suffix(apk.suffix + ".part")
            subprocess.run(["curl", "--fail", "--location", "--retry", "3", "--continue-at", "-",
                            "--output", str(partial), lock["url"]], check=True)
            if partial.stat().st_size != lock["size"] or digest(partial) != lock["sha256"]:
                raise ValueError("Downloaded APK checksum mismatch; partial file retained")
            partial.replace(apk)
    apk = Path(apk)
    if apk.stat().st_size != lock["size"] or digest(apk) != lock["sha256"]:
        raise ValueError("Upstream APK does not match upstream.lock.json")
    cached_apk = cache / lock["url"].rsplit("/", 1)[-1]
    if apk.resolve() != cached_apk.resolve() and (
        not cached_apk.is_file() or digest(cached_apk) != lock["sha256"]
    ):
        imported = cached_apk.with_suffix(".import.part")
        shutil.copyfile(apk, imported)
        if digest(imported) != lock["sha256"]:
            raise ValueError("APK changed while importing into build cache")
        imported.replace(cached_apk)
    with tempfile.TemporaryDirectory(prefix="prepare-", dir=cache) as temporary:
        staging = Path(temporary)
        project, runtime = staging / "project", staging / "runtime"
        with zipfile.ZipFile(apk) as source:
            with zipfile.ZipFile(io.BytesIO(source.read("assets/pi.zip"))) as pi:
                unpack(pi, project)
            with zipfile.ZipFile(io.BytesIO(source.read("assets/agent/bundle.zip"))) as bundle:
                unpack(bundle, staging / "bundle", lock["abi"] + "/")
            for entry in source.namelist():
                name = entry.rsplit("/", 1)[-1]
                if entry.startswith(f'lib/{lock["abi"]}/') and (
                    name.startswith("libMaa") or name in {
                        "libc++_shared.so", "libonnxruntime.so", "libopencv_world4.so", "libfastdeploy_ppocr.so"
                    }
                ):
                    target = runtime / "maafw" / name
                    target.parent.mkdir(parents=True, exist_ok=True)
                    target.write_bytes(source.read(entry))
        bundle = staging / "bundle"
        core = json.loads((bundle / "agent-core.json").read_text())
        assert core["python"] == lock["python"] and core["provides"]["maafw"] == lock["maafw"]
        shutil.copytree(bundle / "prefix", runtime / "python")
        shutil.copytree(bundle / "bin", runtime / "python/bin")
        packages = runtime / "python/lib/python3.13/site-packages"
        shutil.copytree(bundle / "site-packages", packages, dirs_exist_ok=True)
        with zipfile.ZipFile(packages / "pure.zip") as pure:
            unpack(pure, packages)
        (packages / "pure.zip").unlink()
        if (bundle / "licenses").exists():
            shutil.copytree(bundle / "licenses", runtime / "licenses")
        shutil.copy2(bundle / "agent-core.json", runtime / "agent-core.json")
        # Standard Python layout is recognized by the shared framework's agent resolver.
        (runtime / "python/bin/python3").chmod(0o755)
        (runtime / "agent").mkdir()
        (runtime / "agent/.runtime-marker").write_text("Python runtime; project agent comes from APK resources.\n")
        entry = project / "agent/android_entry.py"
        entry.write_text('''import os
import runpy
from pathlib import Path
os.environ["MAAFGO_PLATFORM"] = "android"
runpy.run_path(str(Path(__file__).with_name("main.py")), run_name="__main__")
''')
        interface = json.loads((project / "interface.json").read_text())
        interface["agent"] = {"child_exec": "python3", "child_args": ["-u", "agent/android_entry.py"]}
        # Login ends at the terminal. Bridge that screen into the upstream map-based
        # story runner, while retaining its formation/map entry and no-refill policy.
        for task in interface["task"]:
            if task["name"] == "自动推主线（beta）":
                assert task["entry"] == "自动推主线调度"
                task["entry"] = "Android主线入口"
                task["description"] = task["description"].replace("从主线地图", "从终端、主线地图")
        shutil.copy2(ROOT / "tools/android_main_story.json",
                     project / "resource/base/pipeline/Android主线入口.json")
        # JP's continue screen differs from the base Chinese defeat template.
        # Merge into one file: duplicate node names in a resource bundle are invalid.
        jp_battle = project / "resource/jp/pipeline/自动战斗_感知.json"
        jp_nodes = json.loads(jp_battle.read_text()) if jp_battle.exists() else {}
        overrides = json.loads((ROOT / "tools/android_jp_battle.json").read_text())
        if jp_nodes.keys() & overrides.keys():
            raise ValueError("Upstream now defines JP defeat recognition; review Android overrides")
        jp_nodes.update(overrides)
        jp_battle.write_text(json.dumps(jp_nodes, ensure_ascii=False, indent=2) + "\n")
        adapt_loading_waits(project)
        (project / "interface.json").write_text(json.dumps(interface, ensure_ascii=False, indent=2) + "\n")
        # Preserve the upstream locale in the path understood by the shared catalog.
        locale = project / "i18n/zh_cn.json"
        if locale.exists():
            target = project / "locales/interface/zh_cn.json"
            target.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(locale, target)
        for path in (project, runtime):
            (path / MARKER).write_text(json.dumps(lock, indent=2) + "\n")
        validate(project, runtime)
        publish(project, ROOT / "app/src/main/assets/project")
        publish(runtime, ROOT / "runtime")
        print(f'Prepared {lock["tag"]}: {len(interface["task"])} tasks, {len(interface["resource"])} resources, {lock["abi"]}')


def validate(project, runtime):
    required = [
        project / "interface.json", project / "agent/android_entry.py", project / "agent/main.py",
        project / "agent/utils/support_det.onnx", project / "agent/utils/quest_detect.onnx",
        project / "resource/base/model/ocr/rec.onnx", project / "resource/base/model/ocr/det.onnx",
        runtime / "python/bin/python3", runtime / "python/lib/libpython3.13.so",
        runtime / "python/lib/python3.13/site-packages/cv2.so",
        runtime / "python/lib/python3.13/site-packages/maa/agent/agent_server.py",
        runtime / "python/lib/python3.13/site-packages/numpy/_utils/__init__.py",
        runtime / "python/lib/python3.13/site-packages/numpy/_core/__init__.py",
        runtime / "maafw/libMaaFramework.so", runtime / "maafw/libMaaAgentClient.so",
        runtime / "maafw/libMaaAgentServer.so", runtime / "maafw/libonnxruntime.so",
        runtime / "maafw/libMaaAndroidNativeControlUnit.so",
    ]
    for path in required:
        if not path.is_file() or not path.stat().st_size:
            raise ValueError(f"Missing payload component: {path}")
    interface = json.loads((project / "interface.json").read_text())
    removed = {"启动bbc", "关闭bbc", "BBC 配置转 Chaldea 本地队伍", "打开编队与战斗编辑器", "__MXU_KILLPROC__"}
    assert not removed.intersection(task["name"] for task in interface["task"])
    assert not interface.get("import"), "Android interface must be flattened"
    assert all("config" not in p.parts for p in project.rglob("*")), "Never bundle user data"


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--apk", type=Path, help="Use an existing APK; the pinned checksum is still verified")
    args = parser.parse_args()
    prepare(args.apk)
